"""Regenerates src/fast_pair_table.rs from public/assets/config/devices_info_list.json.

Usage (from app/src-tauri):  python scripts/gen_fast_pair_table.py
Only audio SKUs (deviceSpu.type == "earphone") with a 3-byte Fast Pair Model ID are emitted.
The model code (e.g. "B172") is deviceSpu.modelId, the colour is the SKU's colorId.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "public" / "assets" / "config" / "devices_info_list.json"
OUT = ROOT / "src" / "fast_pair_table.rs"

data = json.loads(SRC.read_text(encoding="utf-8"))
rows = {}
for sku in data["deviceSkuResps"]:
    spu = sku.get("deviceSpu") or {}
    if spu.get("type") != "earphone":
        continue
    fp = (sku.get("fastPairId") or "").strip().upper()
    model = (spu.get("modelId") or "").strip().upper()
    color = (sku.get("colorId") or "").strip().upper()
    if not re.fullmatch(r"[0-9A-F]{6}", fp) or not model or not color:
        continue
    entry = (model, color, f'{spu.get("brand", "")} {spu.get("name", "")}'.strip())
    if fp in rows and rows[fp][:2] != entry[:2]:
        raise SystemExit(f"conflicting Fast Pair id {fp}: {rows[fp]} vs {entry}")
    rows[fp] = entry

lines = [
    "// @generated by scripts/gen_fast_pair_table.py from devices_info_list.json. Do not edit by hand.",
    "",
    "/// `(fast_pair_model_id, model_code, color_id)`, sorted by model then colour.",
    "pub const FAST_PAIR_TABLE: &[(&str, &str, &str)] = &[",
]
for fp, (model, color, name) in sorted(rows.items(), key=lambda kv: (kv[1][0], kv[1][1], kv[0])):
    lines.append(f'    ("{fp}", "{model}", "{color}"), // {name}')
lines.append("];")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {len(rows)} entries to {OUT}")
